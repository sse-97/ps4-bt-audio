/* Candidate code signatures for the kernel routines the service locates, derived
 * from the 13.520.001 capture (probe/fw_probe.c -> fw_probe.bin) and verified to
 * match that capture uniquely. The companion matcher is app/sigscan.h; the full
 * rationale is docs/FIRMWARE_SUPPORT.md.
 *
 * READ THIS BEFORE TRUSTING THESE ELSEWHERE: every mask here is cut from ONE
 * firmware, so "this operand byte moves, that opcode byte is fixed" is a hypothesis,
 * not a cross-firmware fact. These make the service "Safe" (locate, then verify the
 * exact bytes, then patch - refuse on any ambiguity); they are not "Validated" for
 * another firmware until a second firmware's bytes confirm which bytes really move.
 *
 * Six of the nine firmware.h offsets are findable this way. The command dispatcher
 * is both COMMAND and FP_COMMAND (one routine, one address), so six signatures
 * cover seven offsets. The remaining two are NOT code and need their referencing
 * instruction read per firmware instead of a pattern:
 *   - CTX_PTR    a data pointer sitting in a zeroed region (no bytes to pattern on);
 *                recovered from the RIP-relative load that reads it.
 *   - FMT_STRING a run inside a string table; its bytes are not distinctive.
 * Bonus: the cache-fingerprint routine's own displacements are BTA_FW_CACHE_FIRST
 * and BTA_FW_CACHE_END, so that data layout is read from the code, not guessed. */
#include "firmware.h"
#include "sigscan.h"

