/* The six kernel routines the service locates by signature, in the BTA_SIG_* order
 * (app/kernel.h). Bytes/masks were cut from the 13.520.001 capture and CONFIRMED on
 * real 13.52 hardware (git d69b950): each resolved to exactly its known_offset, a
 * single match. 0x00 in a mask marks a wildcarded address/displacement byte.
 *
 * The command dispatcher is both the "command" routine and the second fingerprinted
 * prologue (one routine, one address), so six signatures cover the seven code
 * offsets the old firmware table carried. The two non-code addresses (ctx_ptr, a
 * data pointer in a zeroed region; fmt_string, a run inside a string table) are not
 * findable by pattern and live in app/kernel.h's known-firmware table instead.
 *
 * known_offset is the 13.52 address each must resolve to; it exists for the host
 * tests (they pin the derivation to it) and nothing at runtime reads it. On any
 * other firmware these are candidate patterns, not validated ones - but that is
 * safe by construction: a pattern that does not resolve uniquely simply turns its
 * feature off (see docs/FIRMWARE.md). */
#include "kernel.h"

struct bta_kernel_sig {
    const char *name;
    unsigned long known_offset;   /* 13.520.001 offset, for the host tests only */
    struct bta_sig sig;
};

